#!/usr/bin/env node
// Builds src/data/edit-data.ts from a Whisper JSON transcript
// (output of: python -m whisper VIDEO --model medium --output_format json)
//
// Usage:
//   node scripts/build-data-from-whisper.js path/to/transcript.json [video-filename-in-public] [gap-seconds]
//
// Example:
//   node scripts/build-data-from-whisper.js C:\path\to\IMG_0345.json IMG_0345.mp4 0.3
//
// After running, copy your video into remotion-edit/public/ with the same
// filename, then run `npm run preview` to see it in Remotion Studio.

const fs = require("fs");
const path = require("path");

const [, , transcriptPath, videoFileArg, gapArg] = process.argv;

if (!transcriptPath) {
  console.error("Usage: node build-data-from-whisper.js <transcript.json> [video-filename] [gap-seconds]");
  process.exit(1);
}

const videoFile = videoFileArg || "IMG_0345.mp4";
const gapThreshold = gapArg ? parseFloat(gapArg) : 0.3;

const raw = JSON.parse(fs.readFileSync(transcriptPath, "utf-8"));
const segments = (raw.segments || []).map((s) => ({
  start: s.start,
  end: s.end,
  text: (s.text || "").trim(),
}));

if (segments.length === 0) {
  console.error("No segments found in transcript JSON.");
  process.exit(1);
}

// Merge caption segments into speech ranges, splitting wherever the gap
// to the next segment exceeds the threshold (i.e. cut out dead air).
const merged = [];
let curStart = segments[0].start;
let curEnd = segments[0].end;

for (let i = 1; i < segments.length; i++) {
  const seg = segments[i];
  const gap = seg.start - curEnd;
  if (gap > gapThreshold) {
    merged.push({ start: curStart, end: curEnd });
    curStart = seg.start;
    curEnd = seg.end;
  } else {
    curEnd = Math.max(curEnd, seg.end);
  }
}
merged.push({ start: curStart, end: curEnd });

const formatNum = (n) => Math.round(n * 1000) / 1000;

const segmentsLiteral = merged
  .map((s) => `  { start: ${formatNum(s.start)}, end: ${formatNum(s.end)} },`)
  .join("\n");

const captionsLiteral = segments
  .map(
    (s) =>
      `  { start: ${formatNum(s.start)}, end: ${formatNum(s.end)}, text: ${JSON.stringify(
        s.text
      )} },`
  )
  .join("\n");

const outPath = path.join(__dirname, "..", "src", "data", "edit-data.ts");
const existing = fs.readFileSync(outPath, "utf-8");

const fpsMatch = existing.match(/export const FPS = .*/);
const widthMatch = existing.match(/export const SOURCE_WIDTH = .*/);
const heightMatch = existing.match(/export const SOURCE_HEIGHT = .*/);
const colorMatch = existing.match(/export const COLOR_GRADE_FILTER =[\s\S]*?;/);

const output = `// Auto-generated by scripts/build-data-from-whisper.js from:
// ${path.basename(transcriptPath)}

export const VIDEO_FILE = ${JSON.stringify(videoFile)};
${fpsMatch ? fpsMatch[0] : "export const FPS = 30;"}
${widthMatch ? widthMatch[0] : "export const SOURCE_WIDTH = 1080;"}
${heightMatch ? heightMatch[0] : "export const SOURCE_HEIGHT = 1920;"}

// Segments to KEEP, in seconds, in the ORIGINAL video's timeline.
// The gaps between these ranges (dead air / silences) get cut out.
export const SPEECH_SEGMENTS: Array<{ start: number; end: number }> = [
${segmentsLiteral}
];

// Captions, in seconds, in the ORIGINAL video's timeline.
export const CAPTIONS: Array<{ start: number; end: number; text: string }> = [
${captionsLiteral}
];

${colorMatch ? colorMatch[0] : 'export const COLOR_GRADE_FILTER =\n  "brightness(1.08) contrast(1.12) saturate(1.18) sepia(0.04)";'}
`;

fs.writeFileSync(outPath, output);
console.log(`Wrote ${outPath}`);
console.log(`Speech segments kept: ${merged.length}`);
console.log(`Captions: ${segments.length}`);
console.log(`\nNext: copy your video into public/${videoFile}, then run "npm run preview"`);
