#!/usr/bin/env node
// Probes the main video + two overlay clips with ffprobe, copies them into
// public/, and writes src/data/split-screen-data.ts.
//
// Usage:
//   node scripts/build-split-screen.js <main.mp4> <overlay1.mp4> <overlay2.mp4> [overlay1Start] [overlay2Start]
//
// overlay1Start/overlay2Start are seconds into the main video where the
// split-screen begins (defaults: 19.23 and 54.10).

const { execSync } = require("child_process");
const fs = require("fs");
const path = require("path");

const [, , mainPath, overlay1Path, overlay2Path, start1Arg, start2Arg] = process.argv;

if (!mainPath || !overlay1Path || !overlay2Path) {
  console.error(
    "Usage: node build-split-screen.js <main.mp4> <overlay1.mp4> <overlay2.mp4> [overlay1Start] [overlay2Start]"
  );
  process.exit(1);
}

const probe = (file) => {
  const out = execSync(
    `ffprobe -v error -select_streams v:0 -show_entries stream=width,height:format=duration -of json "${file}"`
  ).toString();
  const json = JSON.parse(out);
  return {
    duration: parseFloat(json.format.duration),
    width: json.streams[0].width,
    height: json.streams[0].height,
  };
};

const main = probe(mainPath);
const ov1 = probe(overlay1Path);
const ov2 = probe(overlay2Path);

const start1 = start1Arg ? parseFloat(start1Arg) : 19.23;
const start2 = start2Arg ? parseFloat(start2Arg) : 54.1;

const clampDuration = (start, clipDuration) =>
  Math.max(0, Math.min(clipDuration, main.duration - start));

const overlays = [
  { file: "overlay1.mp4", mainStart: start1, duration: clampDuration(start1, ov1.duration) },
  { file: "overlay2.mp4", mainStart: start2, duration: clampDuration(start2, ov2.duration) },
];

// Avoid the two overlay windows overlapping.
if (overlays[0].mainStart + overlays[0].duration > overlays[1].mainStart) {
  overlays[0].duration = Math.max(0, overlays[1].mainStart - overlays[0].mainStart);
}

const publicDir = path.join(__dirname, "..", "public");
fs.mkdirSync(publicDir, { recursive: true });
fs.copyFileSync(mainPath, path.join(publicDir, "main.mp4"));
fs.copyFileSync(overlay1Path, path.join(publicDir, "overlay1.mp4"));
fs.copyFileSync(overlay2Path, path.join(publicDir, "overlay2.mp4"));

const formatNum = (n) => Math.round(n * 1000) / 1000;

const output = `// Auto-generated by scripts/build-split-screen.js

export const MAIN_VIDEO = "main.mp4";
export const FPS = 30;
export const WIDTH = ${main.width};
export const HEIGHT = ${main.height};

// Total length of the composition (= main video duration), in seconds.
export const MAIN_DURATION = ${formatNum(main.duration)};

// Each overlay splits the screen (top = main video, bottom = overlay clip)
// starting at \`mainStart\` seconds into the main video, for \`duration\` seconds.
export const OVERLAYS: Array<{
  file: string;
  mainStart: number;
  duration: number;
}> = [
  { file: ${JSON.stringify(overlays[0].file)}, mainStart: ${formatNum(overlays[0].mainStart)}, duration: ${formatNum(overlays[0].duration)} },
  { file: ${JSON.stringify(overlays[1].file)}, mainStart: ${formatNum(overlays[1].mainStart)}, duration: ${formatNum(overlays[1].duration)} },
];
`;

const outPath = path.join(__dirname, "..", "src", "data", "split-screen-data.ts");
fs.writeFileSync(outPath, output);

console.log(`Wrote ${outPath}`);
console.log(`Main video: ${main.width}x${main.height}, ${formatNum(main.duration)}s`);
console.log(`Overlay 1: starts at ${formatNum(overlays[0].mainStart)}s, plays for ${formatNum(overlays[0].duration)}s`);
console.log(`Overlay 2: starts at ${formatNum(overlays[1].mainStart)}s, plays for ${formatNum(overlays[1].duration)}s`);
console.log(`\nCopied videos into public/. Next: npm run preview -- --composition SplitScreenEdit`);
